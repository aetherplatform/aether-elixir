defmodule Aether.SDK.Generator do
  @moduledoc """
  Deterministic bindings for the bundled public OpenAPI contracts.

  Run `mix aether.generate` after exporting contracts from the Aether monorepo.
  Run `mix aether.generate --check` to reject stale generated source.
  """

  @platforms ~w(identity events notifications storage webhooks)
  @methods ~w(get post put patch delete head options)
  @ignored ~w(description summary examples example externalDocs title deprecated)

  @doc "Returns generated relative file paths and their complete contents."
  def files(root \\ File.cwd!()) do
    Map.new(Enum.flat_map(@platforms, &platform_files(root, &1)))
  end

  @doc "Writes generated files, or checks them without changing source."
  def run(root \\ File.cwd!(), check? \\ false) do
    expected = files(root)

    changed =
      expected
      |> Enum.filter(fn {path, content} -> File.read(Path.join(root, path)) != {:ok, content} end)
      |> Enum.map(&elem(&1, 0))
      |> Enum.sort()

    if check? do
      if changed == [], do: :ok, else: {:error, changed}
    else
      Enum.each(expected, fn {path, content} ->
        full = Path.join(root, path)
        File.mkdir_p!(Path.dirname(full))
        File.write!(full, content)
      end)

      :ok
    end
  end

  defp platform_files(root, platform) do
    document =
      root |> Path.join("contracts/openapi/#{platform}.json") |> File.read!() |> Jason.decode!()

    schemas = get_in(document, ["components", "schemas"]) || %{}
    namespace = Module.concat([Aether.SDK.Types, Macro.camelize(platform)])

    known =
      schemas
      |> Enum.sort()
      |> Enum.reduce(%{}, fn {name, schema}, acc ->
        Map.put_new(acc, fingerprint(schema), Module.concat(namespace, name))
      end)

    initial = %{namespace: namespace, known: known, types: %{}}

    state =
      schemas
      |> Enum.sort()
      |> Enum.reduce(initial, fn {name, schema}, state ->
        {_schema, state} = annotate(schema, Module.concat(namespace, name), state, true)
        state
      end)

    {operations, state} =
      document["paths"]
      |> Enum.sort()
      |> Enum.flat_map(fn {path, item} ->
        item
        |> Enum.filter(fn {method, _} -> method in @methods end)
        |> Enum.map(fn {method, operation} ->
          {path, method, operation, item["parameters"] || []}
        end)
      end)
      |> Enum.sort_by(fn {_, _, operation, _} -> operation["operationId"] end)
      |> Enum.map_reduce(state, fn {path, method, operation, shared_parameters}, state ->
        name = operation["operationId"]
        base = Module.concat(namespace, Macro.camelize(operation_name(name)))
        {content_type, request_schema} = content_schema(operation["requestBody"])

        {request_schema, state} =
          annotate(request_schema, Module.concat(base, "RequestBody"), state)

        {responses, state} =
          (operation["responses"] || %{})
          # Transport parses API errors into Aether.SDK.Error. Only successful
          # responses need schemas in the generated runtime catalog.
          |> Enum.filter(fn {status, _} ->
            case Integer.parse(status) do
              {code, ""} when code < 400 -> true
              _ -> false
            end
          end)
          |> Enum.sort()
          |> Enum.map_reduce(state, fn {status, response}, state ->
            {_content_type, schema} = content_schema(response)
            {schema, state} = annotate(schema, Module.concat(base, "Response#{status}"), state)

            {{String.to_integer(status), schema}, state}
          end)

        parameters = merge_parameters(shared_parameters, operation["parameters"] || [])

        metadata = %{
          name: name,
          platform: String.to_atom(platform),
          method: String.to_atom(method),
          path: path,
          token_profiles: operation["x-aether-token-profiles"] || [],
          idempotency: operation["x-aether-idempotency"] || "unspecified",
          success_statuses:
            responses |> Enum.map(&elem(&1, 0)) |> Enum.filter(&(&1 >= 200 and &1 < 400)),
          parameters: parameters,
          content_type: content_type,
          request_required: get_in(operation, ["requestBody", "required"]) == true,
          request_schema: request_schema,
          response_schemas: Map.new(responses)
        }

        {{name |> operation_name() |> String.to_atom(), metadata}, state}
      end)

    catalog = Module.concat(Aether.SDK.Generated, Macro.camelize(platform))
    operations = Map.new(operations)

    generated = """
    # Generated by mix aether.generate. Do not edit by hand.
    defmodule #{inspect(catalog)} do
      @moduledoc false
      @operations #{literal(operations)}
      @spec operations() :: map()
      def operations, do: @operations
      @spec operation(atom()) :: map()
      def operation(name), do: Map.fetch!(@operations, name)
    end
    """

    types =
      state.types
      |> Enum.sort_by(fn {module, _} -> Atom.to_string(module) end)
      |> Enum.map_join("\n\n", fn {module, schema} -> type_source(module, schema) end)

    files = [
      {"lib/aether/sdk/generated/#{platform}.ex", format(generated)},
      {"lib/aether/sdk/types/#{platform}.ex",
       format("# Generated by mix aether.generate. Do not edit by hand.\n" <> types)}
    ]

    if platform == "identity" do
      files
    else
      public = Module.concat(Aether.SDK, Macro.camelize(platform))

      functions =
        operations
        |> Enum.sort()
        |> Enum.map_join("\n", fn {name, metadata} ->
          """
          @doc #{inspect("Calls `#{String.upcase(Atom.to_string(metadata.method))} #{metadata.path}`.\n\nSupply `%{path: ..., query: ..., body: ..., headers: ...}` as appropriate for this operation.")}
          @spec #{name}(Aether.SDK.Client.t(), map(), keyword()) :: {:ok, term()} | {:error, Aether.SDK.Error.t()}
          def #{name}(client, request \\\\ %{}, options \\\\ []) do
            Aether.SDK.Transport.request(client, #{inspect(catalog)}.operation(:#{name}), request, options)
          end
          """
        end)

      source = """
      # Generated by mix aether.generate. Do not edit by hand.
      defmodule #{inspect(public)} do
        @moduledoc #{inspect("Public #{Macro.camelize(platform)} operations. Responses use `Aether.SDK.Types.#{Macro.camelize(platform)}` structs where declared by the contract.")}
        #{functions}
      end
      """

      files ++ [{"lib/aether/sdk/#{platform}.ex", format(source)}]
    end
  end

  defp merge_parameters(shared, operation) do
    (shared ++ operation)
    |> Enum.reduce(%{}, fn parameter, acc ->
      Map.put(acc, {parameter["in"], parameter["name"]}, parameter)
    end)
    |> Enum.sort_by(&elem(&1, 0))
    |> Enum.map(&elem(&1, 1))
  end

  defp content_schema(nil), do: {nil, nil}

  defp content_schema(container) do
    content = container["content"] || %{}

    key =
      Enum.find(
        ["application/json", "application/x-www-form-urlencoded"],
        &Map.has_key?(content, &1)
      ) || content |> Map.keys() |> Enum.sort() |> List.first()

    {key, get_in(content, [key, "schema"])}
  end

  defp annotate(schema, module, state, force \\ false)
  defp annotate(nil, _module, state, _force), do: {nil, state}

  defp annotate(schema, suggested, state, force) when is_map(schema) do
    schema = normalized(schema)
    signature = fingerprint(schema)
    module = if force, do: suggested, else: Map.get(state.known, signature, suggested)
    typed? = force or map_size(schema["properties"] || %{}) > 0

    if not force and typed? and Map.has_key?(state.types, module) do
      {Map.fetch!(state.types, module), state}
    else
      state =
        if typed?, do: %{state | known: Map.put_new(state.known, signature, module)}, else: state

      annotate_children(schema, module, state, typed?)
    end
  end

  defp annotate(schema, _module, state, _force), do: {schema, state}

  defp annotate_children(schema, module, state, typed?) do
    props = schema["properties"] || %{}

    {props, state} =
      props
      |> Enum.sort()
      |> Enum.map_reduce(state, fn {name, child}, state ->
        {child, state} = annotate(child, Module.concat(module, Macro.camelize(name)), state)
        {{name, child}, state}
      end)

    schema =
      if Map.has_key?(schema, "properties"),
        do: Map.put(schema, "properties", Map.new(props)),
        else: schema

    {schema, state} =
      Enum.reduce(["items", "additionalProperties"], {schema, state}, fn key, {schema, state} ->
        case schema[key] do
          child when is_map(child) ->
            {child, state} = annotate(child, Module.concat(module, Macro.camelize(key)), state)
            {Map.put(schema, key, child), state}

          _ ->
            {schema, state}
        end
      end)

    {schema, state} =
      Enum.reduce(["oneOf", "anyOf", "allOf"], {schema, state}, fn key, {schema, state} ->
        case schema[key] do
          children when is_list(children) ->
            {children, state} =
              children
              |> Enum.with_index(1)
              |> Enum.map_reduce(state, fn {child, index}, state ->
                annotate(child, Module.concat(module, "#{Macro.camelize(key)}#{index}"), state)
              end)

            {Map.put(schema, key, children), state}

          _ ->
            {schema, state}
        end
      end)

    if typed? do
      schema = Map.put(schema, "x-elixir-module", module)
      {schema, put_in(state.types[module], schema)}
    else
      {schema, state}
    end
  end

  defp type_source(module, schema) do
    props = schema["properties"] || %{}
    fields = props |> Map.keys() |> Enum.sort() |> Map.new(&{&1, String.to_atom(&1)})

    if map_size(props) > 0 do
      defaults = fields |> Map.values() |> Enum.sort() |> Enum.map(&{&1, :__aether_unset__})
      defaults = defaults ++ [additional_properties: %{}]

      field_types =
        props
        |> Enum.sort()
        |> Enum.map_join(",\n", fn {name, property} ->
          "#{inspect(fields[name])} => #{type_expr(property)} | :__aether_unset__"
        end)

      """
      defmodule #{inspect(module)} do
        @moduledoc #{inspect("Contract object. Unset fields are omitted when encoding. Unknown permitted fields are retained in `additional_properties`. Inspect redacts values.")}
        defstruct #{literal(defaults)}
        @type t :: %__MODULE__{#{field_types}, :additional_properties => %{optional(String.t()) => term()}}
        @doc false
        def __schema__, do: #{literal(schema)}
        @doc false
        def __fields__, do: #{literal(fields)}
      end
      defimpl Inspect, for: #{inspect(module)} do
        def inspect(_value, _options), do: "##{inspect(module)}<redacted>"
      end
      """
    else
      """
      defmodule #{inspect(module)} do
        @moduledoc "Contract value or union."
        @type t :: #{type_expr(Map.delete(schema, "x-elixir-module"))}
        @doc false
        def __schema__, do: #{literal(schema)}
      end
      """
    end
  end

  defp type_expr(%{"x-elixir-module" => module}), do: "#{inspect(module)}.t()"
  defp type_expr(%{"const" => value}) when is_boolean(value) or is_nil(value), do: inspect(value)
  defp type_expr(%{"oneOf" => schemas}), do: union_type(schemas)
  defp type_expr(%{"anyOf" => schemas}), do: union_type(schemas)
  defp type_expr(%{"allOf" => [schema | _]}), do: type_expr(schema)

  defp type_expr(%{"type" => types} = schema) when is_list(types),
    do: union_type(Enum.map(types, &Map.put(schema, "type", &1)))

  defp type_expr(%{"type" => "string"}), do: "String.t()"
  defp type_expr(%{"type" => "integer"}), do: "integer()"
  defp type_expr(%{"type" => "number"}), do: "number()"
  defp type_expr(%{"type" => "boolean"}), do: "boolean()"
  defp type_expr(%{"type" => "null"}), do: "nil"
  defp type_expr(%{"type" => "array"} = schema), do: "[#{type_expr(schema["items"] || %{})}]"
  defp type_expr(%{"type" => "object"}), do: "%{optional(String.t()) => term()}"
  defp type_expr(_schema), do: "term()"

  defp union_type(schemas),
    do: schemas |> Enum.map(&type_expr/1) |> Enum.uniq() |> Enum.join(" | ")

  defp operation_name(name), do: name |> String.replace("OAuth", "Oauth") |> Macro.underscore()

  defp fingerprint(schema), do: schema |> normalized() |> :erlang.term_to_binary([:deterministic])

  defp normalized(value) when is_map(value) do
    value
    |> Map.drop(@ignored)
    |> Map.new(fn {key, child} ->
      cleaned =
        cond do
          key in ["properties", "patternProperties", "$defs", "definitions"] and is_map(child) ->
            Map.new(child, fn {name, entry} -> {name, normalized(entry)} end)

          key in [
            "items",
            "additionalProperties",
            "not",
            "if",
            "then",
            "else",
            "contains",
            "propertyNames"
          ] ->
            normalized(child)

          key in ["oneOf", "anyOf", "allOf", "prefixItems"] and is_list(child) ->
            Enum.map(child, &normalized/1)

          true ->
            child
        end

      {key, cleaned}
    end)
  end

  defp normalized(value), do: value

  # Inspect's map order varies between BEAM runs. Emit sorted entries so
  # --check compares the same source bytes in a fresh process.
  defp literal(value) when is_map(value) do
    entries =
      value
      |> Enum.sort_by(fn {key, _} -> literal(key) end)
      |> Enum.map_join(", ", fn {key, child} -> "#{literal(key)} => #{literal(child)}" end)

    "%{" <> entries <> "}"
  end

  defp literal(value) when is_list(value),
    do: "[" <> Enum.map_join(value, ", ", &literal/1) <> "]"

  defp literal(value) when is_tuple(value),
    do: "{" <> (value |> Tuple.to_list() |> Enum.map_join(", ", &literal/1)) <> "}"

  defp literal(value), do: inspect(value, limit: :infinity, printable_limit: :infinity)

  defp format(source),
    do: source |> Code.format_string!() |> IO.iodata_to_binary() |> Kernel.<>("\n")
end
